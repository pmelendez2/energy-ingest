#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# AI-assisted: ChatGPT / GPT-6; 2026-10-08.
#
# Build and package the standalone gb_profile utility for Linux.
#
# Usage:
#   bash scripts/release_gb_profile.sh
#   GB_PROFILE_OFFICIAL_RELEASE=1 bash scripts/release_gb_profile.sh
#
# Run from a Git checkout with Cargo, Python 3, tar, and sha256sum.
# In Docker Compose, CARGO_TARGET_DIR=/target is honored automatically.
# Only x86_64 and aarch64 native builds are supported.

# Fail on command errors, unset variables, or failed pipeline commands.
set -euo pipefail

# Resolve the repository root independently of the caller's directory.
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

# Cargo places output in CARGO_TARGET_DIR when set; the development
# Compose container uses /target instead of the repository's target/.
target_dir="${CARGO_TARGET_DIR:-$root/target}"
binary="$target_dir/release/gb_profile"
dest="$root/dist"

# Read the gb_profile crate version, not the Green Button library version.
# Cargo.toml is the single source of truth for this SemVer value.
version="$(
    cargo metadata --no-deps --format-version 1 |
        python3 -c '
import json
import sys

packages = json.load(sys.stdin)["packages"]
print(next(p["version"] for p in packages
           if p["name"] == "gb_profile"))
'
)"

# Local builds default to development. Official releases must be explicitly
# requested by the release process; optimization alone does not qualify.
: "${GB_PROFILE_OFFICIAL_RELEASE:=0}"

if [[ "$GB_PROFILE_OFFICIAL_RELEASE" == 1 ]]; then
    # A production release must not carry a SemVer prerelease suffix.
    if [[ "$version" == *-* ]]; then
        echo 'Stable releases require a stable SemVer version' >&2
        exit 1
    fi

    # The release tag must exist and resolve to the checked-out commit.
    tag="gb_profile-v${version}"
    if ! git rev-parse -q --verify "refs/tags/$tag" >/dev/null; then
        echo "Release tag not found: $tag" >&2
        exit 1
    fi

    if [[ "$(git rev-parse HEAD)" != \
          "$(git rev-list -n 1 "$tag")" ]]; then
        echo "Release tag must point to HEAD: $tag" >&2
        exit 1
    fi

    # Reject uncommitted tracked changes for official release builds.
    # Untracked files are not checked by this condition.
    if [[ -n "$(git status --porcelain --untracked-files=no)" ]]; then
        echo 'Release source must have no tracked changes' >&2
        exit 1
    fi
fi

# Package only the native Linux architectures supported by this script.
arch="$(uname -m)"
case "$arch" in
    x86_64|aarch64) ;;
    *)
        echo "Unsupported release architecture: $arch" >&2
        exit 1
        ;;
esac

# --locked guarantees Cargo.lock is not silently regenerated.
# --release selects optimized compilation, not the production channel.
cargo build --locked --release -p gb_profile

# Check that the expected compiled executable exists and runs.
"$binary" --version

# Use a temporary staging directory to assemble the archive, and remove
# it on normal exit or when a command fails.
name="gb_profile-v${version}-linux-${arch}"
mkdir -p "$dest"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# Ship the executable, license, and traceable build metadata together.
mkdir -p "$work/$name"
cp "$binary" "$work/$name/gb_profile"
cp LICENSE "$work/$name/LICENSE"

printf '%s\n' \
    "Version: $version" \
    "Git revision: $(git rev-parse HEAD)" \
    "Official release: $GB_PROFILE_OFFICIAL_RELEASE" \
    > "$work/$name/BUILD_INFO.txt"

# Write a compressed tar archive and a SHA-256 sidecar checksum.
# The checksum file uses a relative filename for checking inside dist/.
tar -C "$work" -czf "$dest/$name.tar.gz" "$name"
(
    cd "$dest"
    sha256sum "$name.tar.gz" > "$name.tar.gz.sha256"
)

printf 'Created %s\n' "$dest/$name.tar.gz"

# Display the entire current dist/ directory. Older artifacts may remain;
# this list is not restricted to files generated by the current run.
printf '\nFiles currently in dist/:\n'
printf '%s\n' '-----------------------------'

find "$dest" -maxdepth 1 -type f \
    -printf '%f\t%k KB\n' | sort

printf '\nTotal files: '
find "$dest" -maxdepth 1 -type f | wc -l
